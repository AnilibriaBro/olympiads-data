def canon(org):
    """Одно написание названия вуза: без «ФГБОУ ВО …», без лишних пробелов и с одинаковыми сокращениями."""
    s = org.strip().lstrip('"“«').strip()
    s = re.sub(r"С\s*анкт-\s*П\s*етербургская государствен\s*н\s*ая", "Санкт-Петербургская государственная", s)
    m = re.search(r"высшего образования\s*[“«\"]?(.+?)[”»\"]?\s*$", s)
    if re.match(r"^\s*(федеральн|государственн)", s, re.I) and m:
        s = m.group(1)
    if "Гуманитарно-педагогическая академия" in s:  # филиал КФУ имени Вернадского в Ялте записан двумя способами
        return "Гуманитарно-педагогическая академия — филиал Крымского федерального университета имени В.И. Вернадского"
    s = re.split(r"\s+-\s+филиал|\s*\(филиал\)|\s*\(Филиал[^)]*\)?", s)[0]  # у филиала — его собственное название
    s = s.replace("Санкт - Петербург", "Санкт-Петербург").replace("“", "").replace("”", "").replace("«", "").replace("»", "")
    # Юридическая форма и почётные слова в начале, ведомство в конце — в названии для школьника не нужны
    s = re.sub(r"^(Автономная некоммерческая( образовательная)? организация|Негосударственное образовательное частное учреждение|"
               r"Образовательное частное учреждение|Частное образовательное учреждение)( высшего образования)?\s+", "", s)
    s = re.sub(r"^(Ленинградской области|Московской области|Республики Крым|города Москвы|ордена Трудового Красного Знамени)\s+", "", s)
    s = re.sub(r"\s+Министерства [а-яё ]+Российской Федерации$", "", s)
    s = re.sub(r"\s*\((Институт|ЯРГУ|филиал)[^)]*\)$", "", s)
    s = re.sub(r"\bим\.\s*", "имени ", s)
    s = re.sub(r"(\b[А-ЯЁ])\.\s+(?=[А-ЯЁ]\.)", r"\1.", s)  # «Н. Н. Бурденко» -> «Н.Н. Бурденко»
    s = s.replace("Иммануила Канта", "И. Канта").replace("имени И.Канта", "имени И. Канта")
    s = s.replace("Сибирский государственный академика", "Сибирский государственный университет науки и технологий имени академика")
    return re.sub(r"\s+", " ", s).strip().rstrip(". ")


def vuz_of(org):
    """(id, название, город) или None, если организатор не вуз."""
    if NOT_VUZ.search(org):
        return None
    name = canon(org)
    for pat, vid in KNOWN:
        if re.search(pat, name):
            return vid, name, None
    city = next((c for pat, c in CITY if re.search(pat, name)), "")
    return "v" + format(zlib.crc32(name.lower().encode("utf-8")), "x"), name, city
